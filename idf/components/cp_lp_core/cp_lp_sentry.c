/*
 * HP-side shim for the r99 sentry program (ulp/main_sentry.c).
 *
 * Kept separate from cp_lp_core.c and cp_lp_bench.c for the same reason those
 * are separate from each other: the r88 and r96 numbers are quoted against
 * those two programs, and this one must be able to change without editing them.
 *
 * NOTHING HERE RUNS UNLESS SOMETHING CALLS IT. The two callers are:
 *   * `lpsentry` (src/platform/LpCoreService.cpp, CP_LP_BENCH only), and
 *   * CP_LP_STANDBY's standby path (src/main.cpp, default 0).
 * With both switches off the linker drops this object, the sentry blob and the
 * ulp_lp_core_* driver with it, so the shipping image still contains no
 * accelerator symbol at all (the r87 archive-resolution guard).
 *
 * PIN OWNERSHIP — the one real hazard, stated here rather than discovered:
 * LP_IO wake is only meaningful if the pad is in the RTC IO function, and that
 * is a configuration the HP GPIO driver does not own. So this file takes GPIO2
 * (expander INT / power key) into RTC-IO input mode for the duration of a
 * sentry run and hands it back with rtc_gpio_deinit() on stop. The caller must
 * stop the sentry BEFORE it reads GPIO2 through the normal GPIO path again —
 * which is exactly what the standby guard in main.cpp does, since the resume
 * path re-initialises the pin anyway.
 */
