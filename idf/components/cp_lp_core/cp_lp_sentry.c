static const char* TAG = "cp_lp_sentry";

extern const uint8_t ulp_cp_lp_sentry_bin_start[] asm("_binary_ulp_cp_lp_sentry_bin_start");
extern const uint8_t ulp_cp_lp_sentry_bin_end[] asm("_binary_ulp_cp_lp_sentry_bin_end");

/* The LP-RAM words are declared by the generated mapgen header (included
 * above); re-declaring them here with a different type qualifier is a hard
 * error, so this file only ever reads them through that header. */

/* GPIO2 — the only wake line this board has: expander INT (power key latched
 * inside the TCA9555) wire-ORed with the IMU INT1. It is RTCIO_GPIO2_CHANNEL,
 * i.e. inside SOC_RTCIO_PIN_COUNT (=8), which is what makes LP_IO wake on it
 * possible at all (esp_hal_gpio/esp32s31/rtc_io_periph.c:10-18). */
#define CP_LP_SENTRY_GPIO GPIO_NUM_2

static bool s_pins_owned = false;

static void sentry_take_pins(void) {
  if (s_pins_owned) return;
  /* No pull-up and no pull-down: the line has external gates driving it and a
   * weak pull inside the pad would only fight them. */
  rtc_gpio_init(CP_LP_SENTRY_GPIO);
  rtc_gpio_set_direction(CP_LP_SENTRY_GPIO, RTC_GPIO_MODE_INPUT_ONLY);
  rtc_gpio_pullup_dis(CP_LP_SENTRY_GPIO);
  rtc_gpio_pulldown_dis(CP_LP_SENTRY_GPIO);
  /* Arm the LP-domain wake on the assertion level. Active LOW: the expander
   * holds the line high while idle and the INT latch pulls it down. */
  rtc_gpio_wakeup_enable(CP_LP_SENTRY_GPIO, GPIO_INTR_LOW_LEVEL);
  s_pins_owned = true;
}

static void sentry_release_pins(void) {
  if (!s_pins_owned) return;
  rtc_gpio_wakeup_disable(CP_LP_SENTRY_GPIO);
  /* Back to the plain GPIO function the HP driver expects. */
  rtc_gpio_deinit(CP_LP_SENTRY_GPIO);
  s_pins_owned = false;
}

esp_err_t cp_lp_sentry_start(uint32_t period_us) {
  /* One program on the LP core at a time. */
  ulp_lp_core_stop();

  sentry_take_pins();

  esp_err_t err = ulp_lp_core_load_binary(ulp_cp_lp_sentry_bin_start,
                                          (size_t)(ulp_cp_lp_sentry_bin_end - ulp_cp_lp_sentry_bin_start));
  if (err != ESP_OK) {
    ESP_LOGE(TAG, "load_binary failed: %s", esp_err_to_name(err));
    sentry_release_pins();
    return err;
  }

  /* LP_TIMER | LP_IO: the timer is the sampling clock and the heartbeat that
   * proves the core is still executing; LP_IO is the line that matters. Both
   * are LP-domain wakeups — neither of them wakes the HP core. */
  ulp_lp_core_cfg_t cfg = {
      .wakeup_source = ULP_LP_CORE_WAKEUP_SOURCE_LP_TIMER | ULP_LP_CORE_WAKEUP_SOURCE_LP_IO,
      .lp_timer_sleep_duration_us = period_us,
  };
  err = ulp_lp_core_run(&cfg);
  if (err != ESP_OK) {
    ESP_LOGE(TAG, "run failed: %s", esp_err_to_name(err));
    sentry_release_pins();
    return err;
  }
  return ESP_OK;
}

void cp_lp_sentry_arm(uint32_t mode) { ulp_cp_lp_sentry_mode = mode ? 1u : 0u; }

void cp_lp_sentry_stop(void) {
  /* Ask the program to leave without arming, give it one period of grace, then
   * halt the core and take the pad back. */
  ulp_cp_lp_sentry_stop = 1;
  vTaskDelay(pdMS_TO_TICKS(2));
  ulp_lp_core_stop();
  ulp_cp_lp_sentry_stop = 0;
  sentry_release_pins();
}

