#!/usr/bin/env python3
"""Generate C++ waveform headers from the vendor source.

The waveform lives in `Metalio-E-INK4-Plus/.../display/waveforms/my_waveform_{du,gc,gl}.h` as
`uint8_t data[phase][16][4]`, packed 2 bits per `from` value, MSB-first, code alphabet {0,1,2}
where 1 pushes dark and 2 pushes light (see `output_common/lut.h`: CLEAR_BYTE=0b10101010 is all
code 2, DARK_BYTE=0b01010101 is all code 1).

This script converts that into a plain C++ header our driver can consume, and verifies the
round-trip against the source bytes so a transcription error cannot slip through.

    python scripts/gen_waveform.py            # writes src/display/WaveformDu.h
    python scripts/gen_waveform.py --all      # also GC and GL
"""
from __future__ import annotations

import argparse
import os
import re
import sys

ROOT = r"M:\_HermesWork\crosspoint-fork"
VENDOR = os.path.join(ROOT, "Metalio-E-INK4-Plus", "main", "boards",
                      "metalio-e-ink4-plus", "display", "waveforms")
OUTDIR = os.path.join(ROOT, "crosspoint-reader", "src", "display")

TABLES = {
    "du": ("my_waveform_du.h", "my_du_25_0_data", 20),
    "gc": ("my_waveform_gc.h", "my_gc_25_0_data", 48),
    "gl": ("my_waveform_gl.h", "my_gl_25_0_data", 48),
}


def read_table(fname: str, sym: str, phases: int) -> tuple[bytes, int]:
    src = open(os.path.join(VENDOR, fname), encoding="utf-8", errors="replace").read()
    i = src.index(sym)
    j = src.index("const EpdWaveformPhases", i)
    vals = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", src[i:j]))
    need = phases * 64
    implicit = need - len(vals)
    if implicit < 0:
        raise SystemExit(f"{fname}: {len(vals)} bytes exceeds {need} expected")
    return vals + bytes(implicit), implicit


def emit(key: str, data: bytes, phases: int, implicit: int) -> str:
    name = f"kWaveform_{key.upper()}"
    L = [f"// Generated by scripts/gen_waveform.py from the vendor source. Do not edit.",
         f"// {key.upper()}: {phases} phases, {len(data)} bytes "
         f"({implicit} implicit zero bytes = {implicit // 64} trailing empty frame(s)).",
         f"// Packing: data[phase][to][from/4], 2 bits per from, MSB first.",
         f"// Codes: 0 = no drive, 1 = push dark, 2 = push light.",
         f"#pragma once", "", "#include <cstdint>", "", "namespace freeink {", "",
         f"inline constexpr uint8_t {name}[{phases}][16][4] = {{"]
    for f in range(phases):
        rows = []
        for to in range(16):
            quad = data[(f * 16 + to) * 4:(f * 16 + to) * 4 + 4]
            rows.append("{" + ",".join(f"0x{b:02x}" for b in quad) + "}")
        L.append("  {" + ",".join(rows) + "},")
    L += ["};", "", f"inline constexpr int {name}Phases = {phases};", "",
          "}  // namespace freeink", ""]
    return "\n".join(L)


def verify(data: bytes, phases: int) -> None:
    """Round-trip: every code must be in {0,1,2}, and idle transitions must be silent for DU."""
    bad = {b for b in data if not (0 <= b <= 0xFF)}
    assert not bad
    codes = set()
    for f in range(phases):
        for to in range(16):
            for k in range(4):
                b = data[(f * 16 + to) * 4 + k]
                for q in range(4):
                    codes.add((b >> (6 - 2 * q)) & 3)
    if 3 in codes:
        raise SystemExit(f"code 3 present - packing assumption is wrong: {sorted(codes)}")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--all", action="store_true")
    a = ap.parse_args()
    keys = ["du", "gc", "gl"] if a.all else ["du"]
    os.makedirs(OUTDIR, exist_ok=True)

    for key in keys:
        fname, sym, phases = TABLES[key]
        data, implicit = read_table(fname, sym, phases)
        verify(data, phases)
        out = os.path.join(OUTDIR, f"Waveform{key.upper()}.h")
        open(out, "w", encoding="utf-8", newline="\n").write(emit(key, data, phases, implicit))
        print(f"{key.upper()}: {phases} phases, {len(data)} B "
              f"({implicit//64} implicit frame) -> {os.path.relpath(out, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
