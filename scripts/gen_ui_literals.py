#!/usr/bin/env python3
"""AUDIT2 -- find integer literals used where a UI metric is expected.

WHY THIS EXISTS
    `UITheme::auditUiScale()` walks `kMetricFields[]` and checks that every *metric* moved
    with the density scale. It is structurally blind to the other half of the problem: a
    screen that never reads a metric and writes a pixel number straight into the draw call.
    `U-2` (tab band = literal 50 px on the touch path, `UiTabListActivity.cpp:14`) and `U-3`
    (toggle = literal 28 px, `UiListActivity.cpp:964`) are both invisible to the runtime
    audit for exactly that reason -- and both were found on glass instead.

    A literal lives in the source, not in the running image, so this cannot be evaluated on
    the device. It is evaluated at BUILD time instead: the findings are compiled into the
    firmware as a static table (`lib/UiLiteralAudit/UiLiteralAudit.generated.h`) and the boot
    path writes them to `/.crosspoint/debug.log` next to the UISCALE line. That makes the
    class readable at boot, from a logtail, without a host-side step.

WHAT IT MATCHES (deliberately narrow -- this is a report, not a proof)
    `name = <integer literal>;` where
      * `name` looks like geometry (height, width, size, inset, radius, padding, spacing,
        gap, margin, thickness, band, tab, button, toggle, slider, touch), and
      * the value is a plain decimal literal in 3..4096 (0/1/2 and -1 are flags and
        sentinels, not lengths), and
      * the line is not a comparison and not a comment.
    Names that are bounds, timeouts or percentages are dropped: they are not drawn lengths
    (MAX_/MIN_ bounds, *_MS/Ms millisecond windows, *PERCENT/Percent, *BYTES, *COUNT, CHUNK).
    Everything else is reported, including legitimate theme constants -- the point is a
    complete list to triage, not a pre-judged one.

USAGE
    python scripts/gen_ui_literals.py            # regenerate lib/UiLiteralAudit/*.generated.h
    python scripts/gen_ui_literals.py --print    # print the full list, write nothing
    python scripts/gen_ui_literals.py --print --only src/activities/UiTabListActivity.cpp
Exit status is 0 in every case, including findings: this is READ-ONLY reporting. A failing
build gate would be a policy decision, and it is not this script's to make.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
SRC = REPO / "src"
OUT = REPO / "lib" / "UiLiteralAudit" / "UiLiteralAudit.generated.h"

SOURCE_SUFFIXES = (".cpp", ".h", ".hpp", ".cc")

# `name = 42;` -- a plain literal, no expression on the right-hand side.
ASSIGN = re.compile(r"\b([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(-?\d{1,5})\s*;")

GEOMETRY = re.compile(
    r"(?i)(height|width|insets?|radius|padding|spacing|gap|margin|thickness|rowh|row_h|"
    r"band|tab|button|toggle|slider|touch|fontsize|font_size)"
)

# Names that are not drawn lengths even though they may contain a geometry word.
NOT_A_LENGTH = re.compile(r"(?i)(max_|min_|_ms$|ms$|percent|bytes|_count$|count$|chunk|_step$|step$)")

COMPARISON = ("==", ">=", "<=", "!=")


def scan(path: pathlib.Path) -> list[tuple[str, int, str, int, str]]:
    hits: list[tuple[str, int, str, int, str]] = []
    rel = path.relative_to(SRC).as_posix()
    for lineno, line in enumerate(path.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
        stripped = line.strip()
        if stripped.startswith(("//", "*", "/*")):
            continue
        if any(op in line for op in COMPARISON):
            continue
        for m in ASSIGN.finditer(line):
            name, value = m.group(1), int(m.group(2))
            if not GEOMETRY.search(name):
                continue
            if NOT_A_LENGTH.search(name):
                continue
            if value in (0, 1, 2) or value < 3 or value > 4096:
                continue
            hits.append((rel, lineno, name, value, stripped))
    return hits


def collect(only: str | None = None) -> list[tuple[str, int, str, int, str]]:
    files = sorted(p for p in SRC.rglob("*") if p.suffix in SOURCE_SUFFIXES)
    rows: list[tuple[str, int, str, int, str]] = []
    for p in files:
        if only and only.replace("\\", "/") not in p.as_posix():
            continue
        rows.extend(scan(p))
    return rows


def render(rows: list[tuple[str, int, str, int, str]]) -> str:
    files = sorted({r[0] for r in rows})
    out = [
        "// GENERATED by scripts/gen_ui_literals.py -- DO NOT EDIT.",
        "//",
        "// AUDIT2: integer literals used where a UI metric is expected (a drawn band height, row",
        "// height or control size written as a number instead of read from ThemeMetrics). This is",
        "// the class UITheme::auditUiScale() cannot see, because it checks metrics that exist and",
        "// these are metrics that were never consulted. Reported at boot to /.crosspoint/debug.log.",
        "#pragma once",
        "",
        "namespace uiLiteralAuditGen {",
        "",
        f"static constexpr int kFileCount = {len(files)};",
        f"static constexpr int kCount = {len(rows)};",
        "",
        "// One short string per finding: \"<path relative to src/>:<line> <name>=<literal>\".",
        "static const char* const kEntries[] = {",
    ]
    for rel, lineno, name, value, _text in rows:
        out.append(f'    "{rel}:{lineno} {name}={value}",')
    if not rows:
        out.append('    "",')
    out += [
        "};",
        "",
        "}  // namespace uiLiteralAuditGen",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description="Report unscaled integer literals in UI code (AUDIT2).")
    ap.add_argument("--print", action="store_true", help="print the findings, write no file")
    ap.add_argument("--only", default=None, help="restrict to paths containing this substring")
    args = ap.parse_args()

    rows = collect(args.only)

    if args.print:
        for rel, lineno, name, value, text in rows:
            print(f"{rel}:{lineno}\t{name}={value}\t| {text}")
        print(f"\n{len(rows)} literal(s) in {len({r[0] for r in rows})} file(s)")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(rows), encoding="utf-8", newline="\n")
    print(f"gen_ui_literals: {len(rows)} literal(s) in {len({r[0] for r in rows})} file(s) -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
